RESOURCE_PATTERNS = {
    "user_seconds": re.compile(r"^\s*User time \(seconds\):\s*([0-9.]+)\s*$"),
    "system_seconds": re.compile(r"^\s*System time \(seconds\):\s*([0-9.]+)\s*$"),
    "elapsed": re.compile(
        r"^\s*Elapsed \(wall clock\) time \(h:mm:ss or m:ss\):\s*(\S+)\s*$"
    ),
    "max_rss_kb": re.compile(
        r"^\s*Maximum resident set size \(kbytes\):\s*(\d+)\s*$"
    ),
    "exit_status": re.compile(r"^\s*Exit status:\s*(\d+)\s*$"),
}


class BenchmarkError(RuntimeError):
    """Raised when a benchmark input, run, or resource gate differs."""


def sha256_path(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def write_json(path: Path, value: object) -> None:
    path.write_text(
        json.dumps(value, indent=2, sort_keys=True) + "\n",
        encoding="ascii",
        newline="\n",
    )


def elapsed_seconds(value: str) -> float:
    parts = value.split(":")
    if len(parts) == 2:
        minutes, seconds = parts
        return 60 * int(minutes) + float(seconds)
    if len(parts) == 3:
        hours, minutes, seconds = parts
        return 3600 * int(hours) + 60 * int(minutes) + float(seconds)
    raise BenchmarkError(f"unrecognized GNU time elapsed value: {value}")


def parse_resource_log(value: str) -> dict[str, object]:
    observed: dict[str, object] = {}
    for line in value.splitlines():
        for key, pattern in RESOURCE_PATTERNS.items():
            match = pattern.match(line)
            if match is None:
                continue
            raw = match.group(1)
            if key == "elapsed":
                observed["elapsed_text"] = raw
                observed["elapsed_seconds"] = elapsed_seconds(raw)
            elif key in {"max_rss_kb", "exit_status"}:
                observed[key] = int(raw)
            else:
                observed[key] = float(raw)
    required = {
        "user_seconds",
        "system_seconds",
        "elapsed_text",
        "elapsed_seconds",
        "max_rss_kb",
        "exit_status",
    }
    missing = sorted(required - observed.keys())
    if missing:
        raise BenchmarkError(f"GNU time report is incomplete: {missing}")
    return observed


def strip_dimacs_comments(value: bytes) -> tuple[bytes, int]:
    lines = value.splitlines(keepends=True)
    kept: list[bytes] = []
    comments = 0
    for line in lines:
        if line.startswith(b"c "):
            comments += 1
        else:
            kept.append(line)
    result = b"".join(kept)
    if comments != 2 or not result.startswith(b"p cnf 3930 474332\n"):
        raise BenchmarkError(
            "raw branch-02 DIMACS comments/header differ from the pinned input"
        )
    return result, comments


def lean_source(theorem: str, cnf: Path, proof: Path) -> str:
    cnf_literal = json.dumps(cnf.as_posix())
    proof_literal = json.dumps(proof.as_posix())
    return (
        "import Mathlib.Tactic.Sat.FromLRAT\n\n"
        "open Lean Elab Term Command\n"
        "open Sat\n\n"
        'elab "e058_lrat_aux_file " n:ident ppSpace cnfPath:str '
        "ppSpace lratPath:str : command => do\n"
        "  let name := (← getCurrNamespace) ++ n.getId\n"
        "  let cnf ← IO.FS.readFile cnfPath.getString\n"
        "  let lrat ← IO.FS.readFile lratPath.getString\n"
        "  Command.liftTermElabM do\n"
        "    let (_, _, _, proof) ←\n"
        "      Mathlib.Tactic.Sat.fromLRATAux cnf lrat name\n"
        "    let type ← Meta.inferType proof\n"
        "    addDecl <| Declaration.thmDecl {\n"
        "      name, levelParams := [], type, value := proof\n"
        "    }\n\n"
        "set_option maxHeartbeats 0 in\n"
        f"e058_lrat_aux_file {theorem}\n"
        f"  {cnf_literal}\n"
        f"  {proof_literal}\n\n"
        f"#print axioms {theorem}\n"
    )


def pinned_input_record(path: Path, raw: bytes, prefix: str) -> dict[str, object]:
    record = {
        f"{prefix}_container_bytes": path.stat().st_size,
        f"{prefix}_container_sha256": sha256_path(path),
        f"{prefix}_raw_bytes": len(raw),
        f"{prefix}_raw_sha256": sha256_bytes(raw),
    }
    expected = {
        key: value for key, value in EXPECTED_INPUT.items() if key.startswith(prefix)
    }
    if record != expected:
        raise BenchmarkError(f"pinned {prefix} input differs: {record}")
    return record


def validate_environment(lean_root: Path, lake: Path) -> dict[str, object]:
    toolchain = (lean_root / "lean-toolchain").read_text(encoding="ascii").strip()
    manifest_path = lean_root / "lake-manifest.json"
    if toolchain != LEAN_TOOLCHAIN:
        raise BenchmarkError(f"Lean toolchain pin differs: {toolchain}")
    if sha256_path(manifest_path) != LAKE_MANIFEST_SHA256:
        raise BenchmarkError("complete Lake package manifest hash differs")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    mathlib = next(
        package for package in manifest["packages"] if package["name"] == "mathlib"
    )
    if mathlib["rev"] != MATHLIB_REVISION:
        raise BenchmarkError(f"mathlib revision pin differs: {mathlib['rev']}")
    version = subprocess.run(
        [str(lake), "env", "lean", "--version"],
        cwd=lean_root,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if (
        version.returncode != 0
        or "Lean (version 4.32.0" not in version.stdout
        or f"commit {LEAN_COMMIT}" not in version.stdout
    ):
        raise BenchmarkError(f"unexpected Lean version: {version.stdout.strip()}")
    lean = lake.parent / "lean"
    if not lean.is_file():
        raise BenchmarkError("Lean executable beside Lake is missing")
    return {
        "lean_toolchain": LEAN_TOOLCHAIN,
        "lean_commit": LEAN_COMMIT,
        "mathlib_revision": MATHLIB_REVISION,
        "lake_manifest_sha256": LAKE_MANIFEST_SHA256,
        "lake_sha256": sha256_path(lake),
        "lean_sha256": sha256_path(lean),
        "version_output": version.stdout.strip(),
    }


def run_import(
    *,
    label: str,
    theorem: str,
    cnf: Path,
    proof: Path,
    lake: Path,
    lean_root: Path,
    work: Path,
    output: Path,
    timeout_seconds: int,
    memory_mib: int,
) -> dict[str, object]:
    source_path = work / f"{label}.lean"
    retained_source = output / f"e058-branch02-benchmark-{label}.lean"
    olean_path = work / f"{label}.olean"
    import_log = output / f"e058-branch02-benchmark-{label}.log"
    resource_log = output / f"e058-branch02-benchmark-{label}-resources.log"
    try:
        cnf_argument = cnf.relative_to(lean_root)
        proof_argument = proof.relative_to(lean_root)
    except ValueError as error:
        raise BenchmarkError(
            f"{label}: benchmark inputs are outside the Lean package root"
        ) from error
    source_text = lean_source(theorem, cnf_argument, proof_argument)
    source_path.write_text(source_text, encoding="utf-8", newline="\n")
    shutil.copyfile(source_path, retained_source)
    lean = lake.parent / "lean"
    if not lean.is_file():
        raise BenchmarkError(f"{label}: Lean executable beside Lake is missing")
    command = [
        str(lake),
        "env",
        str(TIME_BINARY),
        "-v",
        "-o",
        str(resource_log),
        "timeout",
        "--signal=TERM",
        "--kill-after=10",
        str(timeout_seconds),
        str(lean),
        "-j1",
        f"-M{memory_mib}",
        "-o",
        str(olean_path),
        str(source_path),
    ]
    environment = {
        **os.environ,
        "LC_ALL": "C",
        "LANG": "C",
        "TZ": "UTC",
    }
    result = subprocess.run(
        command,
        cwd=lean_root,
        env=environment,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    import_log.write_text(result.stdout, encoding="utf-8", newline="\n")
    if not resource_log.is_file():
        raise BenchmarkError(f"{label}: GNU time did not write its report")
    resources = parse_resource_log(resource_log.read_text(encoding="utf-8"))
    expected_axioms = f"'{theorem}' depends on axioms: [propext]"
    if result.returncode != 0 or resources["exit_status"] != 0:
        raise BenchmarkError(
            f"{label}: Lean import returned {result.returncode}; "
            f"see {import_log} and {resource_log}"
        )
    if result.stdout.strip() != expected_axioms:
        raise BenchmarkError(f"{label}: unexpected Lean output: {result.stdout!r}")
    if "warning:" in result.stdout.lower():
        raise BenchmarkError(f"{label}: Lean emitted a warning")
    if resources["elapsed_seconds"] > timeout_seconds:
        raise BenchmarkError(f"{label}: exceeded the wall-time cap")
    memory_cap_kb = memory_mib * 1024
    if resources["max_rss_kb"] > memory_cap_kb:
        raise BenchmarkError(f"{label}: exceeded the resident-memory cap")
    if not olean_path.is_file():
        raise BenchmarkError(f"{label}: Lean did not write the object file")
    return {
        "label": label,
        "theorem": theorem,
        "command": command,
        "source_path": retained_source.name,
        "source_bytes": retained_source.stat().st_size,
        "source_sha256": sha256_path(retained_source),
        "cnf_bytes": cnf.stat().st_size,
        "cnf_sha256": sha256_path(cnf),
        "proof_bytes": proof.stat().st_size,
        "proof_sha256": sha256_path(proof),
        "olean_bytes": olean_path.stat().st_size,
        "olean_sha256": sha256_path(olean_path),
        "axioms": ["propext"],
        "import_log": {
            "path": import_log.name,
            "bytes": import_log.stat().st_size,
            "sha256": sha256_path(import_log),
        },
        "resource_log": {
            "path": resource_log.name,
            "bytes": resource_log.stat().st_size,
            "sha256": sha256_path(resource_log),
        },
        "resources": resources,
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", type=Path, default=REPOSITORY)
    parser.add_argument("--lake", type=Path, required=True)
    parser.add_argument("--output-directory", type=Path, required=True)
    parser.add_argument("--timeout-seconds", type=int, default=300)
    parser.add_argument("--memory-mib", type=int, default=8192)
    args = parser.parse_args()

    repository = args.project.resolve()
    lean_root = repository / "formal/lean"
    lake = args.lake.resolve()
    output = args.output_directory.resolve()
    if (
        repository != REPOSITORY.resolve()
        or not (lean_root / "lakefile.toml").is_file()
    ):
        raise SystemExit("E058-BRANCH02-BENCHMARK-FAILED: project root differs")
    if not lake.is_file() or not TIME_BINARY.is_file():
        raise SystemExit("E058-BRANCH02-BENCHMARK-FAILED: tool is missing")
    if args.timeout_seconds != 300 or args.memory_mib != 8192:
        raise SystemExit(
            "E058-BRANCH02-BENCHMARK-FAILED: preregistered caps differ"
        )
    output.mkdir(parents=True, exist_ok=True)
    prefix = "e058-branch02-benchmark-"
    collisions = sorted(path.name for path in output.glob(f"{prefix}*"))
    if collisions:
        raise SystemExit(
            "E058-BRANCH02-BENCHMARK-FAILED: output collision: "
            + ", ".join(collisions)
        )

    source_cnf = repository / "artifacts/e038_brooks_branches/branch_02.cnf.xz"
    source_lrat = (
        repository / "certificates/e038_brooks_branches/branch_02.lrat.xz"
    )
    try:
        environment_record = validate_environment(lean_root, lake)
        with lzma.open(source_cnf, "rb") as stream:
            raw_cnf = stream.read()
        with lzma.open(source_lrat, "rb") as stream:
            raw_lrat = stream.read()
        input_record = {
            **pinned_input_record(source_cnf, raw_cnf, "cnf"),
            **pinned_input_record(source_lrat, raw_lrat, "lrat"),
        }
        kernel_cnf, removed_comments = strip_dimacs_comments(raw_cnf)
        kernel_record = {
            "removed_comment_lines": removed_comments,
            "bytes": len(kernel_cnf),
            "sha256": sha256_bytes(kernel_cnf),
        }
        if (
            kernel_record["bytes"] != EXPECTED_INPUT["kernel_cnf_bytes"]
            or kernel_record["sha256"] != EXPECTED_INPUT["kernel_cnf_sha256"]
        ):
            raise BenchmarkError("comment-free raw kernel CNF differs")

        work = lean_root / ".e058-branch02-benchmark-work"
        if work.exists() or work.is_symlink():
            raise BenchmarkError(f"benchmark work path already exists: {work}")
        work.mkdir()
        try:
            raw_kernel_cnf = work / "branch_02.raw-kernel.cnf"
            raw_proof = work / "branch_02.raw.lrat"
            raw_kernel_cnf.write_bytes(kernel_cnf)
            raw_proof.write_bytes(raw_lrat)

            core_cnf = work / "branch_02.core.cnf"
            core_proof = work / "branch_02.core.lrat"
            core_map = work / "branch_02.core-map.json"
            core_receipt_path = work / "branch_02.core-receipt.json"
            core_receipt = minimize(
                source_cnf=source_cnf,
                source_proof=source_lrat,
                output_cnf=core_cnf,
                output_proof=core_proof,
                map_path=core_map,
                receipt_path=core_receipt_path,
            )
            observed_core = {
                key: core_receipt["core"][key] for key in EXPECTED_CORE
            }
            if observed_core != EXPECTED_CORE:
                raise BenchmarkError(f"regenerated core differs: {observed_core}")

            raw = run_import(
                label="raw",
                theorem="E058Branch02RawProofOnly",
                cnf=raw_kernel_cnf,
                proof=raw_proof,
                lake=lake,
                lean_root=lean_root,
                work=work,
                output=output,
                timeout_seconds=args.timeout_seconds,
                memory_mib=args.memory_mib,
            )
            reduced = run_import(
                label="reduced",
                theorem="E058Branch02ReducedProofOnly",
                cnf=core_cnf,
                proof=core_proof,
                lake=lake,
                lean_root=lean_root,
                work=work,
                output=output,
                timeout_seconds=args.timeout_seconds,
                memory_mib=args.memory_mib,
            )
        finally:
            shutil.rmtree(work)

        receipt = {
            "schema_version": 1,
            "experiment": "E058-R5-SPECIAL-BROOKS-KERNEL-BRIDGE",
            "benchmark": "PREREGISTERED-E038-BRANCH-02-RAW-CORE-COMPARISON",
            "scope": (
                "Proof-only pinned-Mathlib import of the exact E038 branch-02 "
                "raw formula/certificate and its deterministic backward RUP core"
            ),
            "limits": {
                "wall_seconds_per_import": args.timeout_seconds,
                "lean_memory_mib": args.memory_mib,
                "resident_memory_gate_kb": args.memory_mib * 1024,
            },
            "environment": environment_record,
            "input": input_record,
            "raw_kernel_cnf": kernel_record,
            "core": core_receipt["core"],
            "tools": {
                "runner": {
                    "path": str(Path(__file__).resolve().relative_to(REPOSITORY)),
                    "sha256": sha256_path(Path(__file__).resolve()),
                },
                "core_slicer": {
                    "path": "src/minimize_rup_lrat.py",
                    "sha256": sha256_path(
                        repository / "src/minimize_rup_lrat.py"
                    ),
                },
                "lake": {
                    "path": str(lake),
                    "sha256": sha256_path(lake),
                },
            },
            "records": [raw, reduced],
            "comparison": {
                "wall_speedup": (
                    raw["resources"]["elapsed_seconds"]
                    / reduced["resources"]["elapsed_seconds"]
                ),
                "max_rss_reduction_fraction": (
                    1
                    - reduced["resources"]["max_rss_kb"]
                    / raw["resources"]["max_rss_kb"]
                ),
            },
            "verification": "LEAN-KERNEL-PROOF-ONLY-COMPARISON",
            "allowed_axioms": ["propext"],
            "complete": True,
        }
        receipt_path = output / "e058-branch02-benchmark-receipt.json"
        write_json(receipt_path, receipt)
        print(
            "E058-BRANCH02-BENCHMARK-PASS "
            f"raw_seconds={raw['resources']['elapsed_seconds']} "
            f"raw_max_rss_kb={raw['resources']['max_rss_kb']} "
            f"reduced_seconds={reduced['resources']['elapsed_seconds']} "
            f"reduced_max_rss_kb={reduced['resources']['max_rss_kb']} "
            f"receipt_sha256={sha256_path(receipt_path)}"
        )
        return 0
    except (
        BenchmarkError,
        KeyError,
        OSError,
        StopIteration,
        TypeError,
        ValueError,
        lzma.LZMAError,
        subprocess.SubprocessError,
    ) as error:
        raise SystemExit(f"E058-BRANCH02-BENCHMARK-FAILED: {error}") from error


if __name__ == "__main__":
    raise SystemExit(main())
