"""Reproduce the preregistered E058 branch-02 raw/core Lean comparison.

Both imports use Mathlib's proof-producing ``fromLRATAux`` implementation and
retain only the resulting ``Sat.Fmla.proof _ []`` theorem.  The raw input is
the exact committed E038 branch-02 pair with its two DIMACS comment lines
removed because Mathlib's parser does not accept comments.  The reduced input
is regenerated by the committed deterministic backward RUP slicer.
"""

